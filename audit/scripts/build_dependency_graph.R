# Builds audit/dependency_graph.csv and audit/dependency_graph.md from a static parse of the
# scripts (pipeline/tests/testthat/helper-depgraph.R). Run from the repo root.

source("pipeline/tests/testthat/helper-depgraph.R")
g <- dg_build(".")
live <- dg_live_scripts(".")
li <- dg_live_inputs(g, DG_RAW_INPUTS)

# local file times (outputs older than their inputs = stale)
mt <- function(p) ifelse(file.exists(p), format(file.mtime(p), "%Y-%m-%d %H:%M"), NA)
g$exists <- !is.na(g$path) & file.exists(ifelse(is.na(g$path), "", g$path))
g$mtime <- ifelse(g$exists, mt(g$path), NA)
write.csv(g[order(g$script_class, g$script, g$direction, g$path), ], "audit/dependency_graph.csv", row.names = FALSE)

stale <- list()
for (s in live) {
  ins <- unique(na.omit(g$path[g$script == s & g$direction == "read"]))
  outs <- unique(na.omit(g$path[g$script == s & g$direction == "write"]))
  ins <- setdiff(ins[file.exists(ins)], outs) # ignore files the script itself rewrites
  outs <- outs[file.exists(outs) & grepl("\\.(rds|csv)$", outs)]
  if (!length(ins) || !length(outs)) next
  newest_in <- max(file.mtime(ins))
  old <- outs[as.numeric(difftime(newest_in, file.mtime(outs), units = "secs")) > 60]
  if (length(old)) {
    stale[[s]] <- data.frame(script = s, output = old, output_mtime = mt(old),
                             newest_input = ins[which.max(file.mtime(ins))], input_mtime = mt(ins[which.max(file.mtime(ins))]))
  }
}
stale <- do.call(rbind, stale)

hard <- system("grep -n '/Users/' pipeline/*.R pipeline/R/*.R 2>/dev/null", intern = TRUE)
expl <- unique(g[g$script_class == "live" & g$direction == "read" & grepl("^exploratory/", g$path), c("script", "path")])
unres <- g[g$script_class == "live" & is.na(g$path), c("script", "direction", "call")]

md <- c(
  "# Dependency graph (static parse of the scripts)",
  "",
  "Generated by `audit/scripts/build_dependency_graph.R` from a static parse of `pipeline/*.R` and",
  "`exploratory/**/*.R` (no code executed). Machine-readable edge list: `audit/dependency_graph.csv`",
  "(script, direction, path, call, script class, exists, local mtime). Live scripts = the `CLAUDE.md` run order.",
  "",
  sprintf("Edges: %d (%d unresolved paths, listed below). Live scripts: %d.", nrow(g), sum(is.na(g$path)), length(live)),
  "",
  "## Inputs of live scripts and their producers",
  "",
  "| Live script | Reads | Status | Producer(s) |",
  "|---|---|---|---|",
  sprintf("| `%s` | `%s` | %s | %s |", sub("^pipeline/", "", li$script), li$path, li$status,
          ifelse(nzchar(li$producers_live), li$producers_live, li$producers_other)),
  "",
  "## Flags",
  "",
  "### Live inputs produced only outside the run order",
  "",
  if (any(grepl("FLAG", li$status))) sprintf("- `%s` reads `%s`: %s (%s)", li$script[grepl("FLAG", li$status)],
                                              li$path[grepl("FLAG", li$status)], li$status[grepl("FLAG", li$status)],
                                              li$producers_other[grepl("FLAG", li$status)]) else "- none",
  "",
  "### Live scripts reading from `exploratory/`",
  "",
  if (nrow(expl)) sprintf("- `%s` reads `%s`", expl$script, expl$path) else "- none",
  "",
  "### Hard-coded absolute paths in pipeline code",
  "",
  if (length(hard)) paste0("- `", hard, "`") else "- none",
  "",
  "### Outputs older than their newest input (local mtimes, .rds/.csv only)",
  "",
  if (!is.null(stale) && nrow(stale)) sprintf("- `%s`: `%s` (%s) older than `%s` (%s)", stale$script, stale$output,
                                              stale$output_mtime, stale$newest_input, stale$input_mtime) else "- none",
  "",
  "Checked by hand (12 Nov 2026): `h2h3_wb_model_objects.rds` was rewritten at 17:04 by the 26-34 min",
  "sensitivity run's restore to 30 min; its `data` (haul_id, residual, FP_between, FP_within, year, stat_rec) is",
  "identical to `primary_model_v2.rds$data`, so the phase_v2 outputs are not stale in substance.",
  "`validate_haul_effort_alignment.R` reads `primary_model_v2.rds` only to report which previous hauls changed.",
  "",
  "### Unresolved paths in live scripts (parser could not resolve; mostly log sinks and figures)",
  "",
  if (nrow(unres)) sprintf("- `%s`: %s via `%s()`", unres$script, unres$direction, unres$call) else "- none",
  "",
  "## Scripts out of scope (listed as untested)",
  "",
  "- Stale per `outputs/live_pipeline_run_log.md`: `run_h1_presentation_figures.R`, `fig_state_variable_distributions.R`,",
  "  `explore_h1_catchability_scaling.R`, `explore_h1_dominance_partial_r2.R`, `run_h2h3_car_reporting_diagnostics.R`,",
  "  `explore_h1_haul_dominance.R`.",
  "- Archived after GATE A (untracked, moved to `archive/figure_scripts/`): `fig_methods_state_and_fishing_pressure.R`,",
  "  `fig_study_area_intro.R`, `run_methods_study_area_visuals.R`, `run_h2h3_phase_v2_rectangle_maps.R`,",
  "  `run_h2_presentation_primary_figure.R`.",
  sprintf("- Other `pipeline/` scripts not in the run order: %s.",
          paste0("`", sort(setdiff(unique(g$script[g$script_class == "pipeline_other"]), character())), "`", collapse = ", "))
)
writeLines(md, "audit/dependency_graph.md")
cat("Wrote audit/dependency_graph.md and audit/dependency_graph.csv\n")
cat("Flags:", sum(grepl("FLAG", li$status)), " stale outputs:", if (is.null(stale)) 0 else nrow(stale), "\n")
